def test_inverse_consistency_is_measured_not_assumed() -> None:
    # §39: the backward transform is estimated independently, so composing it
    # with the forward one is a real test.
    angle = 0.3
    rotation = torch.tensor([
        [math.cos(angle), -math.sin(angle), 0.0], [math.sin(angle), math.cos(angle), 0.0], [0.0, 0.0, 1.0],
    ])
    translation = torch.tensor([1.0, 2.0, 0.0])
    forward = _assignment(4, rotation, translation, torch.ones(4, dtype=torch.bool))

    inverse_rotation = rotation.T[None].repeat(4, 1, 1)
    inverse_translation = (-rotation.T @ translation)[None].repeat(4, 1)
    good = verify_inverse_consistency(forward, inverse_rotation, inverse_translation)
    check(float(good["tangent_error"].max()) < 1.0e-4, "a genuinely inverse pair composes to the identity")

    bad = verify_inverse_consistency(forward, inverse_rotation, inverse_translation + 1.0)
    check(
        float(bad["translation_error"].min()) > 0.5,
        "and a wrong backward estimate is detected rather than hidden by construction",
    )


