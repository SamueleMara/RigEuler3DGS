def test_static_scene_has_no_dynamic_mode() -> None:
    xyz = irregular_cloud(600, seed=1, extent=2.0)
    generator = torch.Generator().manual_seed(2)
    moved = xyz + torch.randn(xyz.shape, generator=generator) * 0.002

    posterior = compute_motion_posterior(xyz, moved, local_scale(xyz), local_scale(moved))
    check(
        float(posterior.forward_mismatch.max()) < 0.1,
        "an unmoved scene has a forward mismatch far below one local scale",
    )
    # The mixture will always fit two components; what matters is that it
    # reports the scene as not genuinely bimodal rather than inventing a
    # dynamic population out of the static noise.
    check(
        posterior.stats["spatial_detector_uncertain"] or float(posterior.stats["source_separation"]) < 4.0,
        "a static scene is reported as having no well-separated dynamic mode",
    )


def test_mixture_recovers_a_planted_bimodal_split() -> None:
    generator = torch.Generator().manual_seed(3)
    static = torch.exp(torch.randn(900, generator=generator) * 0.4 - 2.0)
    dynamic = torch.exp(torch.randn(100, generator=generator) * 0.4 + 3.0)
    fit = fit_two_component_log_mismatch_mixture(torch.cat((static, dynamic)))
    check(fit.bimodal, "a genuinely bimodal mismatch distribution is recognised as bimodal")
    check(
        abs(fit.dynamic_weight - 0.10) < 0.05,
        f"and the dynamic component's weight matches the planted 10% ({fit.dynamic_weight:.3f})",
    )
    posterior = fit.posterior(torch.log(torch.cat((static, dynamic)) + 1.0e-8))
    truth = torch.cat((torch.zeros(900, dtype=torch.bool), torch.ones(100, dtype=torch.bool)))
    check(
        float(((posterior > 0.5) == truth).float().mean()) > 0.97,
        "MAP classification from the posterior recovers the planted split without a threshold",
    )


def test_mixture_needs_no_threshold_across_very_different_scenes() -> None:
    # The same code, no arguments changed, on scenes where 5% and 60% moved.
    generator = torch.Generator().manual_seed(5)
    for fraction in (0.05, 0.60):
        count = 1000
        dynamic_count = int(count * fraction)
        static = torch.exp(torch.randn(count - dynamic_count, generator=generator) * 0.4 - 2.0)
        dynamic = torch.exp(torch.randn(dynamic_count, generator=generator) * 0.4 + 3.0)
        fit = fit_two_component_log_mismatch_mixture(torch.cat((static, dynamic)))
        check(
            abs(fit.dynamic_weight - fraction) < 0.06,
            f"the fitted dynamic fraction tracks the truth at {fraction:.0%} "
            f"(got {fit.dynamic_weight:.3f}) with nothing retuned",
        )


