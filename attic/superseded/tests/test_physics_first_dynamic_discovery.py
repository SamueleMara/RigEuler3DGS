def test_refilled_region_defeats_xyz_but_not_the_hierarchy() -> None:
    static = irregular_cloud(200, seed=41, extent=1.5)
    moving = irregular_cloud(200, seed=42, extent=1.5, centre=(4.0, 0.0, 0.0))
    static_t = irregular_cloud(200, seed=141, extent=1.5)
    filler = irregular_cloud(200, seed=43, extent=1.5, centre=(4.0, 0.0, 0.0))
    shift = torch.tensor([6.0, 0.0, 0.0])

    xyz0 = torch.cat((static, moving), dim=0)
    xyzT = torch.cat((static_t, moving + shift, filler), dim=0)
    is_dynamic = torch.zeros(int(xyz0.shape[0]), dtype=torch.bool)
    is_dynamic[200:] = True

    posterior = compute_motion_posterior(xyz0, xyzT, local_scale(xyz0), local_scale(xyzT))
    forward = posterior.forward_mismatch
    ratio = float(forward[is_dynamic].median()) / max(float(forward[~is_dynamic].median()), 1.0e-9)
    check(
        0.3 < ratio < 3.0,
        f"the refilled region makes absolute mismatch nearly uninformative (ratio {ratio:.2f}), "
        f"which is exactly why stage 1 may not be asked where anything went",
    )

    # The patch metric, by contrast, still knows: the moved block's patches
    # are isometric to their own displaced copies and to nothing else.
    knn, _ = build_full_geometry_knn(xyz0, 24)
    patches = build_nested_metric_patches(xyz0, knn)
    idx, valid = gather_patches(patches, torch.arange(200, 210))
    displaced = xyz0[idx] + shift
    residual = float(torch.cdist(displaced.reshape(-1, 3), (moving + shift)).min(dim=1).values.max())
    spacing = float(torch.cdist(moving, moving).masked_fill(
        torch.eye(int(moving.shape[0]), dtype=torch.bool), float("inf")
    ).min(dim=1).values.median())
    check(
        residual < 0.05 * spacing,
        f"the moved patches exist verbatim in frame T, so a metric test can find them "
        f"(residual {residual:.4f} against spacing {spacing:.4f})",
    )


