"""P10 -- flow matching on transport that physics already validated.

The difference from the existing endpoint flow matching in this repo is the
supervision, not the network.  ``train_endpoint_flow_matching`` samples a
TARGET GAUSSIAN from a transport plan, which makes FM responsible for
correspondence; §34 and §40 forbid that, because there is no Gaussian
identity between two independently trained models and any such target is
partly invented.

Here the endpoint is generated by the accepted rigid transform:

    y_hat_i = R_p x_i + t_p,     v* = y_hat_i - x_i

so FM only has to learn the continuous field that interpolates motion the
metric, rigid, agreement and render stages already accepted.  The target
cloud was used to infer the transform and its job ended there.

The network, the positional encoding and the integrator are the project's
existing ``EndpointFlowMLP`` and ``integrate_flow``: this stage changes what
FM is taught, not how it is built.

§41: the loss is the flow-matching loss and nothing else.  Where rigidity
has to be enforced it is enforced by ARCHITECTURE (§42's twist field), never
by adding a weighted rigidity term.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

import torch
import torch.nn.functional as F
from torch import nn

from utils.endpoint_flow_matching import EndpointFlowMLP, FlowMatchingConfig
from utils.progress import bar, write


class TwistFieldMLP(nn.Module):
    """§42: predict an ``se(3)`` twist per point, not a free Cartesian velocity.

    The velocity of a rigid body at ``x`` is ``omega x x + v``, so a network
    that emits ``(omega, v)`` and evaluates that expression can only ever
    produce an instantaneously rigid field.  Rigidity is then structural: it
    holds exactly, at initialisation, for any weights, and there is no
    ``lambda_rigid`` to balance against the data term.

    Reuses the existing ``EndpointFlowMLP`` encoder so this is the project's
    network with a different head, not a second architecture.
    """

    def __init__(self, hidden_dim: int = 128, layers: int = 4, posenc_frequencies: int = 6):
        super().__init__()
        self.backbone = EndpointFlowMLP(hidden_dim, layers, posenc_frequencies)
        width = self.backbone.net[0].out_features
        # Replace the 3-vector head with a 6-vector twist head.
        self.backbone.net[-1] = nn.Linear(width, 6)

    def twist(self, xyz: torch.Tensor, tau: torch.Tensor) -> torch.Tensor:
        return self.backbone(xyz, tau)

    def forward(self, xyz: torch.Tensor, tau: torch.Tensor) -> torch.Tensor:
        twist = self.twist(xyz, tau)
        omega, linear = twist[:, :3], twist[:, 3:]
        return torch.cross(omega, xyz, dim=-1) + linear


@dataclass
class TransformFlowResult:
    """A trained field plus the honest record of what it was trained on."""

    model: nn.Module
    logs: list[dict[str, float]] = field(default_factory=list)
    stats: dict[str, Any] = field(default_factory=dict)


def build_flow_model(cfg: FlowMatchingConfig, *, parameterisation: str = "twist") -> nn.Module:
    """``twist`` (§42, preferred) or ``cartesian`` (the existing MLP)."""
    if parameterisation == "twist":
        return TwistFieldMLP(cfg.hidden_dim, cfg.layers)
    if parameterisation == "cartesian":
        return EndpointFlowMLP(cfg.hidden_dim, cfg.layers)
    raise ValueError(f"unknown parameterisation {parameterisation!r}")


def train_transform_flow_matching(
    source_xyz: torch.Tensor,
    endpoint_xyz: torch.Tensor,
    cfg: FlowMatchingConfig,
    *,
    parameterisation: str = "twist",
    device: str | torch.device | None = None,
    desc: str = "P10 flow matching",
) -> TransformFlowResult:
    """Train on ``x_i -> y_hat_i`` pairs. No target Gaussian is ever consulted.

    ``endpoint_xyz`` must be transform-generated (``T_i x_i``).  Passing a
    nearest-target cloud here would silently reintroduce the identity
    assumption this whole architecture exists to avoid, so the caller is
    responsible for where it came from -- and the probe gets it from
    ``generate_forward_fm_pairs``.
    """
    device = torch.device(device or ("cuda" if torch.cuda.is_available() else "cpu"))
    source = torch.as_tensor(source_xyz).detach().float().to(device)
    endpoint = torch.as_tensor(endpoint_xyz).detach().float().to(device)
    if source.shape != endpoint.shape:
        raise ValueError("source and transform-derived endpoint must align one-to-one")
    if int(source.shape[0]) == 0:
        raise ValueError("no supervised pairs: nothing passed the physical stages")

    model = build_flow_model(cfg, parameterisation=parameterisation).to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=max(float(cfg.lr), 1.0e-8))
    generator = torch.Generator(device=device).manual_seed(int(cfg.seed))

    # Centring is numerical, not a modelling choice: the positional encoding
    # saturates on COLMAP coordinates far from the origin.
    origin = source.mean(dim=0, keepdim=True)
    source_c, endpoint_c = source - origin, endpoint - origin

    logs: list[dict[str, float]] = []
    progress = bar(range(max(1, int(cfg.iters))), desc=desc, unit="iter", leave=True)
    for iteration in progress:
        batch = min(int(cfg.batch_size), int(source.shape[0]))
        ids = torch.randint(0, int(source.shape[0]), (batch,), device=device, generator=generator)
        x0, x1 = source_c[ids], endpoint_c[ids]
        tau = torch.rand(batch, device=device, generator=generator)
        xt = x0 + tau[:, None] * (x1 - x0)          # §40's deterministic path
        target_velocity = x1 - x0                    # §40's target velocity

        prediction = model(xt, tau)
        loss = F.mse_loss(prediction, target_velocity)   # §41: this and nothing else
        if not bool(torch.isfinite(loss)):
            raise RuntimeError("flow matching produced a non-finite loss")

        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        optimizer.step()

        if iteration % 25 == 0 or iteration == int(cfg.iters) - 1:
            with torch.no_grad():
                displacement = float(target_velocity.norm(dim=1).mean())
                relative = float(loss.detach()) ** 0.5 / max(displacement, 1.0e-8)
            row = {
                "iteration": int(iteration),
                "loss": float(loss.detach()),
                "rmse": float(loss.detach()) ** 0.5,
                "mean_displacement": displacement,
                "relative_error": relative,
            }
            logs.append(row)
            progress.set_postfix({
                "loss": f"{row['loss']:.4g}",
                "rmse/|d|": f"{relative:.3f}",
            })
    progress.close()

    return TransformFlowResult(
        model=model,
        logs=logs,
        stats={
            "parameterisation": parameterisation,
            "pairs": int(source.shape[0]),
            "final_loss": logs[-1]["loss"] if logs else float("nan"),
            "final_relative_error": logs[-1]["relative_error"] if logs else float("nan"),
            "mean_displacement": float((endpoint - source).norm(dim=1).mean()),
            "origin": [float(v) for v in origin.reshape(-1)],
        },
    )


@torch.no_grad()
def integrate_transform_flow(
    model: nn.Module,
    source_xyz: torch.Tensor,
    cfg: FlowMatchingConfig,
    *,
    origin: torch.Tensor | None = None,
) -> torch.Tensor:
    """Integrate the learned field from tau=0 to tau=1, same scheme as the repo's."""
    device = next(model.parameters()).device
    x = torch.as_tensor(source_xyz).detach().float().to(device)
    shift = torch.zeros((1, 3), device=device) if origin is None else torch.as_tensor(origin).to(device).reshape(1, 3)
    x = x - shift
    steps = max(1, int(cfg.integration_steps))
    dt = 1.0 / float(steps)
    for step in range(steps):
        tau = torch.full((int(x.shape[0]),), step * dt, device=device)
        x = x + dt * model(x, tau)
    return x + shift


@torch.no_grad()
def evaluate_flow_against_transform(
    model: nn.Module,
    source_xyz: torch.Tensor,
    endpoint_xyz: torch.Tensor,
    cfg: FlowMatchingConfig,
    *,
    origin: torch.Tensor | None = None,
) -> dict[str, float]:
    """Does the integrated flow reproduce the transform it was taught?

    This is the only thing FM is being asked to do here, so it is the only
    thing worth reporting: a low training loss on a field that integrates
    somewhere else is not success.
    """
    integrated = integrate_transform_flow(model, source_xyz, cfg, origin=origin)
    target = torch.as_tensor(endpoint_xyz).detach().float().to(integrated.device)
    error = torch.linalg.norm(integrated - target, dim=1)
    displacement = torch.linalg.norm(target - torch.as_tensor(source_xyz).float().to(target.device), dim=1)
    return {
        "endpoint_error_mean": float(error.mean()),
        "endpoint_error_median": float(error.median()),
        "endpoint_error_p90": float(torch.quantile(error, 0.90)),
        "mean_displacement": float(displacement.mean()),
        "relative_endpoint_error": float(error.mean() / displacement.mean().clamp_min(1.0e-8)),
    }


@torch.no_grad()
def verify_velocity_inverse_consistency(
    forward_model: nn.Module,
    backward_model: nn.Module,
    xyz: torch.Tensor,
    *,
    samples: int = 8,
) -> dict[str, float]:
    """§32/§39: ``v_F(x_t, t) + v_B(x_t, 1-t) ~ 0`` for independently trained fields.

    A validation condition, not a construction identity.  The backward field
    is trained on its own endpoint's transforms, so agreement here is
    evidence; had it been defined as the analytic inverse it would hold
    trivially and test nothing.
    """
    device = next(forward_model.parameters()).device
    x = torch.as_tensor(xyz).detach().float().to(device)
    errors = []
    for step in range(max(1, int(samples))):
        tau = float(step) / float(max(1, int(samples) - 1)) if int(samples) > 1 else 0.5
        t_forward = torch.full((int(x.shape[0]),), tau, device=device)
        t_backward = torch.full((int(x.shape[0]),), 1.0 - tau, device=device)
        residual = forward_model(x, t_forward) + backward_model(x, t_backward)
        errors.append(float(torch.linalg.norm(residual, dim=1).median()))
    return {
        "median_inverse_residual": float(sum(errors) / len(errors)),
        "per_tau": errors,
    }
