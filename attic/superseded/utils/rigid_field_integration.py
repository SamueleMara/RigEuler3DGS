"""Exact integration of factorized rigid Killing velocity fields."""

from __future__ import annotations

import torch

from utils.rigid_killing_motion import integrate_rigid_mode_exact
from utils.rigid_transform_utils import matrix_to_quaternion


def _integrated_coordinate(temporal_speed, timestamps, t_a, t_b):
    speed = torch.as_tensor(temporal_speed).detach().cpu().double().reshape(-1)
    time = torch.as_tensor(timestamps).detach().cpu().double().reshape(-1)
    if time.numel() != speed.numel() + 1:
        raise ValueError("timestamps must contain one more value than temporal_speed")
    if not bool((torch.diff(time) > 0).all()):
        raise ValueError("timestamps must be strictly increasing")
    first, second = float(t_a), float(t_b)
    sign = 1.0
    if second < first:
        first, second, sign = second, first, -1.0
    if first < float(time[0]) - 1.0e-9 or second > float(time[-1]) + 1.0e-9:
        raise ValueError("integration interval lies outside timestamps")
    left = torch.maximum(time[:-1], torch.tensor(first, dtype=time.dtype))
    right = torch.minimum(time[1:], torch.tensor(second, dtype=time.dtype))
    overlap = (right - left).clamp_min(0.0)
    return sign * torch.sum(speed * overlap)


@torch.no_grad()
def integrate_rigid_field(spatial_mode, temporal_speed, t_a, t_b, timestamps):
    """Return the exact SE(3) transform generated by a rigid velocity field.

    ``spatial_mode=None`` is the physical zero field and therefore returns the
    identity transform.  Moving transforms are derived only from the integral
    of the supplied temporal speed; no transform trajectory is optimized here.
    """
    coordinate = (
        torch.tensor(0.0, dtype=torch.float64)
        if spatial_mode is None and temporal_speed is None
        else _integrated_coordinate(temporal_speed, timestamps, t_a, t_b)
    )
    dtype = torch.float64
    identity = torch.eye(3, dtype=dtype)
    if spatial_mode is None:
        rotation = identity
        translation = torch.zeros(3, dtype=dtype)
        quaternion = torch.tensor([1.0, 0.0, 0.0, 0.0], dtype=dtype)
    else:
        origin = torch.zeros((1, 3), dtype=dtype)
        orientation = torch.tensor([[1.0, 0.0, 0.0, 0.0]], dtype=dtype)
        result = integrate_rigid_mode_exact(
            origin,
            spatial_mode.to(device="cpu", dtype=dtype),
            coordinate,
            orientations=orientation,
        )
        rotation = result["rotation_matrix"].double()
        translation = result["positions"][0].double()
        quaternion = matrix_to_quaternion(rotation).double()
    transform = torch.eye(4, dtype=dtype)
    transform[:3, :3] = rotation
    transform[:3, 3] = translation
    return {
        "R_ab": rotation,
        "t_ab": translation,
        "T_ab": transform,
        "q_ab": quaternion,
        "integrated_coordinate": coordinate,
        "source_of_truth": "integrated_rigid_velocity_field",
    }
