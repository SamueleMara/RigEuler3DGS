"""URDF for ManiSkill / SAPIEN (spec 6A), generated from the CanonicalAsset only.

Two links (static_link root, moving_link child), one joint `articulation_joint`:
    <origin xyz = o, rpy = fixed-axis RPY of R_B_J0>   (= T_B_J0)
    <axis xyz = "0 0 1">
    <limit lower upper> = PHYSICAL stops (or an explicitly labelled observed-range preview), effort, velocity (SI)
    <dynamics damping friction>  viscous damping, Coulomb friction
<inertial> per link: COM origin in the link frame, full symmetric inertia in link-frame axes (rpy = 0).
<collision> per convex proxy, mesh vertices already in the link frame (origin identity). No <visual>: the 3DGS PLYs
are rendered by a Gaussian adapter from live link poses (asset.yaml / object.yaml), never as URDF meshes.
The root is fixed by the simulator setup (ManiSkill / SAPIEN fix_root_link); no world link is invented.
"""
from __future__ import annotations

import xml.etree.ElementTree as ET
from pathlib import Path

from .model import CanonicalAsset
from .schema import JOINT_NAME


def _f(x) -> str:
    return repr(float(x))


def _v(xs) -> str:
    return " ".join(_f(x) for x in xs)


def urdf_text(a: CanonicalAsset, model_dir_rel_to_asset="maniskill") -> str:
    p = a.physics
    if p is None:
        raise ValueError("URDF needs validated physics (collision, inertia, physical joint limits)")
    depth = len(Path(model_dir_rel_to_asset).parts)
    up = "/".join([".."] * depth)
    robot = ET.Element("robot", name=a.name)
    robot.append(ET.Comment(f" GENERATED by RigEuler3DGS sim-asset export from Phase 5 of {a.scene}; frames: "
                            f"static_link = Wc (capture world), moving_link = J0 (anchor q = 0, +Z = joint axis). "
                            f"Joint limits: {p.joint.limits_provenance}. "))
    for lk in ("static_link", "moving_link"):
        L = ET.SubElement(robot, "link", name=lk)
        i = p.inertial[lk]
        ine = ET.SubElement(L, "inertial")
        ET.SubElement(ine, "origin", xyz=_v(i.com), rpy="0 0 0")
        ET.SubElement(ine, "mass", value=_f(i.mass))
        I = i.inertia
        ET.SubElement(ine, "inertia", ixx=_f(I[0, 0]), ixy=_f(I[0, 1]), ixz=_f(I[0, 2]), iyy=_f(I[1, 1]),
                      iyz=_f(I[1, 2]), izz=_f(I[2, 2]))
        for k, rel in enumerate(a.collision_files[lk]["parts"]):
            c = ET.SubElement(L, "collision", name=f"{lk}_collision_{k:03d}")
            ET.SubElement(c, "origin", xyz="0 0 0", rpy="0 0 0")
            g = ET.SubElement(c, "geometry")
            ET.SubElement(g, "mesh", filename=f"{up}/{rel}")
    J = ET.SubElement(robot, "joint", name=JOINT_NAME, type=a.joint_type)
    ET.SubElement(J, "parent", link="static_link")
    ET.SubElement(J, "child", link="moving_link")
    ET.SubElement(J, "origin", xyz=_v(a.joint_origin_xyz), rpy=_v(a.joint_origin_rpy))
    ET.SubElement(J, "axis", xyz="0 0 1")
    jl = p.joint
    ET.SubElement(J, "limit", lower=_f(jl.lower), upper=_f(jl.upper), effort=_f(jl.effort), velocity=_f(jl.velocity))
    ET.SubElement(J, "dynamics", damping=_f(jl.damping), friction=_f(jl.coulomb_friction))
    ET.indent(robot, space="  ")
    return '<?xml version="1.0"?>\n' + ET.tostring(robot, encoding="unicode") + "\n"


def write_urdf(a: CanonicalAsset, path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(urdf_text(a))
    return path
