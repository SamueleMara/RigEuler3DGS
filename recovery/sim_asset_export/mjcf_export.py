"""MJCF for MuJoCo (spec 6C), generated from the CanonicalAsset only.

    <worldbody>
      <body name="static_link" pos/quat = T_W_B>          (no joint: welded to the world = fixed base)
        <inertial pos=COM mass fullinertia>              (link frame; MuJoCo diagonalises)
        <geom type="mesh" .../> per convex proxy        (vertices already in the link frame)
        <body name="moving_link" pos/quat = T_B_J0>
          <inertial .../>
          <joint name="articulation_joint" type="hinge"|"slide" axis="0 0 1" pos="0 0 0" range=[stops]
                 damping (viscous) frictionloss (Coulomb) [armature]/>
          <geom .../>
Engine-specific semantics (documented, not claimed identical to PhysX):
  * collision: MuJoCo collides with the CONVEX HULL of each mesh geom -> we only pass validated convex proxies
  * friction: one sliding coefficient = contact.dynamic_friction (no static/dynamic split); restitution not mapped
  * effort limit -> actuatorfrcrange (only bounds actuator forces; the joint is passive -> no effect)
  * velocity limit: MuJoCo has no joint velocity limit -> NOT_REPRESENTED
  * gravity: option gravity = (0, 0, -9.81) in W
The 3DGS PLYs are not MJCF geometry; an external gsplat adapter reads xpos/xquat of the physics bodies.
"""
from __future__ import annotations

import xml.etree.ElementTree as ET
from pathlib import Path

from .frames import quat_wxyz_from_R
from .model import GRAVITY_W, CanonicalAsset
from .schema import JOINT_NAME


def _f(x) -> str:
    return repr(float(x))


def _v(xs) -> str:
    return " ".join(_f(x) for x in xs)


NOT_REPRESENTED = {"velocity_limit": "MuJoCo has no joint velocity limit",
                   "contact.static_friction": "MuJoCo uses one sliding friction coefficient (dynamic_friction)",
                   "contact.restitution": "MuJoCo contacts are parameterised by solref / solimp, not restitution",
                   "effort_limit": "written as actuatorfrcrange; bounds actuator force only (passive joint)"}


def mjcf_text(a: CanonicalAsset) -> str:
    p = a.physics
    if p is None:
        raise ValueError("MJCF needs validated physics")
    m = ET.Element("mujoco", model=a.name)
    m.append(ET.Comment(f" GENERATED by RigEuler3DGS sim-asset export ({a.scene}); body frames = URDF link frames "))
    ET.SubElement(m, "compiler", angle="radian", meshdir="../physics/collision", inertiafromgeom="false",
                  autolimits="true")
    ET.SubElement(m, "option", gravity=_v(GRAVITY_W))
    asset = ET.SubElement(m, "asset")
    names = {}
    for lk in ("static_link", "moving_link"):
        names[lk] = []
        for k, rel in enumerate(a.collision_files[lk]["parts"]):
            nm = f"{lk}_collision_{k:03d}"
            ET.SubElement(asset, "mesh", name=nm, file=Path(rel).name)
            names[lk].append(nm)
    geom_kw = {}
    if p.contact is not None:
        geom_kw["friction"] = f"{_f(p.contact['dynamic_friction'])} 0.005 0.0001"
    wb = ET.SubElement(m, "worldbody")

    def body(parent, lk, T):
        b = ET.SubElement(parent, "body", name=lk, pos=_v(T[:3, 3]), quat=_v(quat_wxyz_from_R(T[:3, :3])))
        i = p.inertial[lk]
        I = i.inertia
        ET.SubElement(b, "inertial", pos=_v(i.com), mass=_f(i.mass),
                      fullinertia=_v([I[0, 0], I[1, 1], I[2, 2], I[0, 1], I[0, 2], I[1, 2]]))
        return b
    bs = body(wb, "static_link", a.T_W_B)
    for nm in names["static_link"]:
        ET.SubElement(bs, "geom", name=nm, type="mesh", mesh=nm, **geom_kw)
    bm = body(bs, "moving_link", a.T_B_J0)
    jl = p.joint
    jkw = dict(name=JOINT_NAME, type="hinge" if a.joint_type == "revolute" else "slide", axis="0 0 1", pos="0 0 0",
               range=_v([jl.lower, jl.upper]), damping=_f(jl.damping), frictionloss=_f(jl.coulomb_friction),
               actuatorfrcrange=_v([-jl.effort, jl.effort]))
    if jl.armature is not None:
        jkw["armature"] = _f(jl.armature)
    ET.SubElement(bm, "joint", **jkw)
    for nm in names["moving_link"]:
        ET.SubElement(bm, "geom", name=nm, type="mesh", mesh=nm, **geom_kw)
    # MuJoCo's parent-child contact filter does not apply to a parent welded to the world, so the jointed pair would
    # collide; PhysX articulations (SAPIEN) and USD joints (physics:collisionEnabled = false) disable it -> exclude
    # explicitly so all three engines share the same contact topology
    con = ET.SubElement(m, "contact")
    ET.SubElement(con, "exclude", body1="static_link", body2="moving_link")
    ET.indent(m, space="  ")
    return ET.tostring(m, encoding="unicode") + "\n"


def write_mjcf(a: CanonicalAsset, path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(mjcf_text(a))
    return path
